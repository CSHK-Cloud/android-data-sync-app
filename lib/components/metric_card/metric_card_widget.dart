    super.key,
    String? label,
    String? value,
    String? unit,
    double? progress,
    String? color,
  })  : this.label = label ?? 'Local (Phone)',
        this.value = value ?? '',
        this.unit = unit ?? 'GB',
        this.progress = progress ?? 0.0,
        this.color = color ?? 'primary';

  final String label;
  final String value;
  final String unit;
  final double progress;
  final String color;

  @override
  State<MetricCardWidget> createState() => _MetricCardWidgetState();
}

